export function getTassHeadlineForMonth(month: number): string {
  const m = Math.max(1, Math.min(36, month));
  return (
    TASS_HISTORICAL_MONTHLY_NEWS[m] ||
    'ТАСС ПЕРЕДАЕТ: ОБСТАНОВКА В СТРАНЕ ОСТАЕТСЯ НАПРЯЖЕННОЙ. ПАРТИЙНЫЕ И СОВЕТСКИЕ ОРГАНЫ ВЕДУТ РАБОТУ ПО СТАБИЛИЗАЦИИ.'
  );
}

export function getTassHeadline(days: number): string {
  const approxMonth = Math.max(1, Math.min(36, Math.floor(days / 21) + 1));
  return getTassHeadlineForMonth(approxMonth);
}
